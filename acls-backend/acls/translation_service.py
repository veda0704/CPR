def translate_to_te(text):
    """
    Translates English text to Telugu using internal mapping.
    Returns original text if no translation found.
    """
    if not text:
        return text
    
    # Normalize line endings to avoid \r\n vs \n mismatch
    normalized_text = text.replace('\r\n', '\n')
    
    # Try exact match
    translated = TELUGU_MAPPINGS.get(normalized_text)
    if translated:
        # logger.debug(f"DEBUG: Found translation for '{normalized_text}' -> '{translated}'")
        return translated
    
    # Try normalized match (strip whitespace)
    stripped_text = normalized_text.strip()
    translated = TELUGU_MAPPINGS.get(stripped_text)
    if translated:
        return translated
        
    logger.warning(f"DEBUG: No translation found for '{text}'")
    return text

